#' @title Remove comments from student code
#' @description Remove R comments from lines of code, e.g. before counting
#' or searching for terms with [rt_count] or [rt_contains].
#' Uses the actual parse tree ([utils::getParseData]), so a `#`
#' inside a string (`"C#"`) is not mistaken for a comment.
#' The line structure is kept: comment-only lines become empty strings,
#' so line numbers remain valid.
#' @return Character vector with one element per line of code, without comments
#'         and without trailing whitespace.
#'         A single `NA_character_` (not one per line) if `code` can not be parsed,
#'         e.g. for a script with a syntax error. This does not happen for a script
#'         that ran successfully in [rt_run_script]. [rt_count] and [rt_contains]
#'         pass this on as `NA` / a warning.
#' @author Berry Boessenkool, \email{berry-b@@gmx.de}, Nov 2026\cr
#'         Function generated by Claude Sonnet 5.5, 2026-11-17
#' @seealso [rt_count], [rt_run_script]
#' @export
#' @importFrom utils getParseData
#' @examples
#' code <- c("# header", "x <- 5 # five", 'y <- "C#" # sharp', "z <- x |> sqrt()")
#' rt_remove_comments(code)
#' rt_count(code, "|>")
#' rt_count(rt_remove_comments(code), "x")
#'
#' @param code Character vector with one element per line of R code,
#'             normally the output of [rt_run_script].
#'             Elements containing line breaks are split into lines,
#'             so the result can be longer than `code`.
#'
rt_remove_comments <- function(code)
{
lines <- code
if(any(grepl("\n", code, fixed=TRUE))) # split elements with line breaks into lines
  lines <- strsplit(paste(code, collapse="\n"), "\n", fixed=TRUE)[[1]]
parsed <- try(parse(text=lines, keep.source=TRUE), silent=TRUE)
if(inherits(parsed, "try-error")) return(NA_character_)
pd <- utils::getParseData(parsed)
if(is.null(pd) || nrow(pd)==0) return(lines)
pd <- pd[pd$token=="COMMENT", ]
# Comments always extend to the end of the line, so they are removed by their
# text (not by column positions, which are unreliable with tabs and unicode).
for(i in seq_len(nrow(pd)))
  {
  l <- pd$line1[i]
  if(endsWith(lines[l], pd$text[i]))
    lines[l] <- substr(lines[l], 1, nchar(lines[l]) - nchar(pd$text[i]))
  }
sub("\\s+$", "", lines)
}
