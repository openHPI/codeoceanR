#' @title Count occurrences of a pattern
#' @description Count how often a pattern occurs in a character vector,
#' e.g. in student code. Combine with [rt_remove_comments] to ignore comments.
#' @details Overlapping matches are not counted separately
#'          (`"aa"` occurs once in `"aaa"`), as in [gregexpr].
#' @return Integer: total number of matches over all elements of `x`
#'         (0 if there are none, also if `x` has length 0).
#'         `NA` if `x` contains `NA`.
#'         An error (for the test author, not students) if `pattern` is not
#'         a single, non-empty, non-NA charstring.
#' @author Berry Boessenkool, \email{berry-b@@gmx.de}, Nov 2026\cr
#'         Function generated by Claude Sonnet 5.5, 2026-11-17
#' @seealso [rt_remove_comments], [rt_contains]
#' @export
#' @examples
#' rt_count(c("a |> b |> c", "d |> e"), "|>")   # 3
#' rt_count("some text", "xyz")                  # 0
#' rt_count("10, 100, 1000", "10")               # 3 (substring matches)
#' rt_count("10, 100, 1000", "\\b10\\b", fixed=FALSE) # 1
#'
#' @param x       Character vector, e.g. lines of code from [rt_run_script].
#' @param pattern Charstring to search for.
#' @param fixed   Literal match instead of regular expression? DEFAULT: TRUE
#'
rt_count <- function(x, pattern, fixed=TRUE)
{
stopifnot(is.character(pattern), length(pattern)==1, !is.na(pattern), nchar(pattern)>0)
if(anyNA(x)) return(NA_integer_)
# gregexpr gives -1 for no match, which has length 1, so count positive positions:
sum(unlist(gregexpr(pattern, x, fixed=fixed)) > 0L)
}
